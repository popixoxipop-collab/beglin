#!/usr/bin/env python3
"""Strict real signed OFF/A/B/C original27 TRAIN16 independent replay, no holds.

The underlying 656-token source files were generated by actual EOE Apple MLX
full27 Gold teacher-forced model jobs, not synthetic fixture data. This CI test
replays sealed source and rejects every source mutation. It is retrospective
TRAIN16 evidence and cannot establish generalization or empirical Fisher.
"""
from __future__ import annotations
import hashlib
import importlib.util
import pathlib
import tempfile
import unittest
from unittest import mock

ROOT=pathlib.Path(__file__).resolve().parents[1]
DATA=ROOT/"docs/research"
SCRIPT=ROOT/"tools/je01_eoe_postnll_bc_true27_independent_nll_audit.py"
EXPECTED={
  "off":("JE01_REAL27_POSTNLL_BC_OFF_656GOLD_NATIVE_20261123.json","1c7fb23fe0de81a75966f945e7308f7d041bc233816bcd9bfcbb34915cdc72ff"),
  "B":("JE01_REAL27_POSTNLL_B_656GOLD_NATIVE_20261123.json","f319144ae53b3391e25797dfa27517c8167a9663b988139b78ea8868dcb7c8ba"),
  "C":("JE01_REAL27_POSTNLL_C_656GOLD_NATIVE_20261123.json","e492c2c00c70d2083cb0169fd61948fb0c3cf2f8e466d5cf564b4ac4d729de6d"),
  "audit":("JE01_REAL27_POSTNLL_A_B_C_656GOLD_INDEPENDENT_PAIRED_AUDIT_20261123.json","1c22cbccb72f461fb10c94f79540922c43a8ec94140fb68fbdf052065239a819"),
}
spec=importlib.util.spec_from_file_location("je01_postnll_bc_real27_native_audit",SCRIPT)
module=importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)


class TestActualJE01Original27BCPairedGoldNLL(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.data={}
        for key,(file,expected_sha) in EXPECTED.items():
            path=DATA/file
            if not path.is_file() or path.is_symlink():
                raise AssertionError("JE01_MISSING_ACTUAL_NATIVE_EOE_RECEIPT_"+key)
            b=path.read_bytes()
            if hashlib.sha256(b).hexdigest()!=expected_sha:
                raise AssertionError("JE01_ACTUAL_EOE_SOURCE_SHA_DRIFT_"+key)
            cls.data[key]=b

    def make_tree(self,root):
        for key in ("off","B","C"):
            directory=root/key
            directory.mkdir(parents=True)
            (directory/"JE01_BC_REAL27_GOLD16_NATIVE_NLL.json").write_bytes(self.data[key])

    def test_real_nll_source_signed_and_native_model(self):
        d={key:module.signed(DATA/fn) for key,(fn,_) in EXPECTED.items() if key!="audit"}
        for key,mode in (("off","off"),("B","B"),("C","C")):
            v=module.validate(d[key],mode)
            self.assertEqual(sum(len(a) for a in v),656)
            self.assertEqual(d[key]["gold_tokens"],656)
            self.assertIs(d[key]["production_modified"],False)
            self.assertEqual(d[key]["heldout_validation128"],"NOT_ACCESSED")
            self.assertEqual(d[key]["heldout_OOD128"],"NOT_ACCESSED")
            self.assertEqual(d[key]["empirical_fisher_weights"],"NOT_MEASURED")
        self.assertEqual(d["off"]["native_output_sha256"],module.ORIGINAL_SHA)
        self.assertEqual(d["off"]["mean_gold_NLL"],module.BASELINE_NLL)
        self.assertGreater(d["B"]["mean_gold_NLL"],d["C"]["mean_gold_NLL"])
        self.assertGreater(d["C"]["mean_gold_NLL"],d["off"]["mean_gold_NLL"])

    def test_actual_native_eoe_paired_recomputation_equals_sealed_audit(self):
        with tempfile.TemporaryDirectory() as d:
            root=pathlib.Path(d)
            self.make_tree(root)
            with mock.patch.object(module,"RUN",root):
                computed=module.audit()
        sealed=module.signed(DATA/EXPECTED["audit"][0])
        self.assertEqual(computed,sealed)
        self.assertEqual(sealed["receipt_sha256"],
                         "c499ec1378e9bfa258b6d30d1bfddbe8530d112dd06708ec55fbcc1896f60c1c")
        self.assertEqual(sealed["cases"],16)
        self.assertEqual(sealed["gold_tokens"],656)
        self.assertEqual(sealed["policy_adoption"],"HOLD")
        self.assertEqual(sealed["true_empirical_Fisher_parameter_matrix"],"NOT_MEASURED")
        self.assertEqual(sealed["independent_validation128"],"NOT_ACCESSED")
        self.assertEqual(sealed["independent_OOD128"],"NOT_ACCESSED")
        for arm in ("OFF_vs_A","OFF_vs_B","OFF_vs_C"):
            self.assertGreater(computed["comparisons"][arm]["delta_NLL"],0)

    def test_a_single_real_token_mutation_rejected_by_signature(self):
        with tempfile.TemporaryDirectory() as d:
            root=pathlib.Path(d)
            self.make_tree(root)
            p=root/"B"/"JE01_BC_REAL27_GOLD16_NATIVE_NLL.json"
            raw=p.read_bytes()
            bad=raw.replace(b"2.2974258514952206",b"2.2974258514952207",1)
            self.assertNotEqual(raw,bad)
            p.write_bytes(bad)
            with mock.patch.object(module,"RUN",root):
                with self.assertRaisesRegex(ValueError,"SIGN"):
                    module.audit()


if __name__=="__main__":
    unittest.main()
