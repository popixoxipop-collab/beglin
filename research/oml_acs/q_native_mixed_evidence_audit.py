def sha(b:bytes)->str:return hashlib.sha256(b).hexdigest()

def private(p:pathlib.Path)->bytes:
    if not p.is_file() or p.is_symlink() or (p.stat().st_mode&0o777)!=0o600:
        raise RuntimeError("private source is missing/unsafe: "+str(p))
    return p.read_bytes()

def role_policy_details():
    original=private(SCAN/"q_196_proxy_results_private.json")
    if sha(original)!=EXPECTED_SCAN_SHA:raise RuntimeError("real 196-tensor scan changed")
    scan=json.loads(original)
    receipt=json.loads(private(MIX/"mixed_lab_source_receipt.json"))
    if receipt.get("source_proxy_evidence_sha256")!=EXPECTED_SCAN_SHA or receipt.get("source_BEGLIN_original_sha256")!=EXPECTED_ORIGINAL_ENGINE_SHA:
        raise RuntimeError("research binary provenance changed")
    if sha(private(MIX/"qwen_infer_q_mixed_lab.c"))!=receipt["mixed_source_sha256"]:
        raise RuntimeError("mixed C code SHA mismatch")
    binary=MIX/"beglin_q_mixed_lab"
    if not binary.is_file() or sha(binary.read_bytes())!=receipt["binary_sha256"]:
        raise RuntimeError("mixed compiled native binary drift")
    rows=scan["rows"]
    if len(rows)!=196 or len({(r["role"],r["layer"]) for r in rows})!=196:
        raise RuntimeError("must cover 196 unique source projections")
    if scan["selected_roles_order"]!=list(ROLE_ORDER):
        raise RuntimeError("role ordering changed")
    cost_and_policy={}
    rng=np.random.default_rng(73)
    expected_random={}
    for role in ROLE_ORDER:
        expected_random[role]=sorted(int(i) for i in rng.choice(28,4,replace=False))
    for name in ("proxy","random"):
        blob=private(MIX/f"policy_{name}.txt")
        if sha(blob)!=receipt["policy_sha256"][name]:
            raise RuntimeError("policy file replaced")
        pairs=[]
        for item in blob.decode().splitlines():
            fields=item.split()
            if len(fields)!=2:raise RuntimeError("bad policy syntax")
            role,layer=fields
            if role not in ROLE_ORDER or not layer.isascii() or not layer.isdigit():
                raise RuntimeError("policy role/layer syntax incorrect")
            pairs.append((role,int(layer)))
        if len(pairs)!=28 or len(set(pairs))!=28:
            raise RuntimeError("policy must contain exactly 28 unique role-layer entries")
        mapping={role:sorted(l for r,l in pairs if r==role) for role in ROLE_ORDER}
        if any(len(mapping[role])!=4 for role in ROLE_ORDER):
            raise RuntimeError("must promote exactly four layers per role")
        expected={role:scan["role_to_layer_selection"][role]["proxy_n8_layers"] if name=="proxy" else expected_random[role] for role in ROLE_ORDER}
        if mapping!=expected:
            raise RuntimeError("policy not genuinely source-only, or seed mismatch")
        selected=set(pairs)
        b=sum(int(x["qng64_8_with_scales_bytes"] if (x["role"],x["layer"]) in selected else x["q4_with_scales_bytes"]) for x in rows)
        if b!=scan["mixed_logical_weight_bytes"][name]:
            raise RuntimeError("storage budget mismatch")
        proxy_loss=sum((x["qng64_8_relative_l2"] if (x["role"],x["layer"]) in selected else x["q4_relative_l2"])**2 for x in rows)
        cost_and_policy[name]=dict(logical_projection_bytes=b,
                                   weights_8bit=28,weights_4bit=168,
                                   role_layer_policy_sha256=receipt["policy_sha256"][name],
                                   sum_squared_normalized_weight_error_proxy=float(proxy_loss),
                                   selected_layers=mapping)
    if cost_and_policy["proxy"]["logical_projection_bytes"]!=cost_and_policy["random"]["logical_projection_bytes"]:
        raise RuntimeError("matched budget control failed")
    return scan,receipt,cost_and_policy

def load_logits(mode:str)->tuple[np.ndarray,str]:
    root=BASIC/mode if mode in ("f32","n8","q4") else MIX/f"mixed_{mode}"
    if not root.is_dir():raise RuntimeError("missing actual tier "+mode)
    for item in ("prompt_ids.i32","eval/ppl_work/w0.i32","eval/ppl_work/w1.i32"):
        private(root/item)
    buf=private(root/"results/c_logits_last.f32")
    if len(buf)!=VOCAB*4:raise RuntimeError("unexpected vocab logits")
    x=np.frombuffer(buf,dtype="<f4").astype(np.float64)
    if not np.isfinite(x).all():raise RuntimeError("nonfinite model outputs")
    return x,sha(buf)

def compare():
    inputfiles=[
     ["prompt_ids.i32","eval/ppl_work/w0.i32","eval/ppl_work/w1.i32"],
    ][0]
    for filename in inputfiles:
        blobs=[private((BASIC/m if m in ("f32","n8","q4") else MIX/f"mixed_{m}")/filename) for m in MODELS]
        if not all(x==blobs[0] for x in blobs):
            raise RuntimeError("PPL/input mismatch across precision tiers")
    xs={}
    hashes={}
    for mode in MODELS:
        xs[mode],hashes[mode]=load_logits(mode)
    ref=xs["f32"]
    prob=np.exp(ref-ref.max());prob/=prob.sum()
    result={}
    baseline_nll=math.log(LOGGED["f32"]["ppl"])
    for mode in MODELS:
        x=xs[mode]
        val=LOGGED[mode]
        if val["ppl_tokens"]!=21 or val["ppl"]<=0 or val["bench_ms_tok"]<=0:
            raise RuntimeError("invalid observed process transcript metric")
        m={
          "logits_sha256":hashes[mode],"top1_id":int(x.argmax()),
          "PPL_transcribed_from_durable_process":val["ppl"],
          "NLL_nats_per_token":math.log(val["ppl"]),
          "relative_NLL_delta_vs_F32":math.log(val["ppl"])/baseline_nll-1,
          "PPL_tokens":21,
          "observed_peak_RSS_bytes":val["ppl_RSS"],
          "bench_best_of_3_one_token_ms":val["bench_ms_tok"],
          "bench_best_of_3_one_token_tps":val["bench_tok_s"],
          "process_PPL":val["ppl_process"],"process_bench":val["bench_process"],
        }
        if mode!="f32":
            q=np.exp(x-x.max());q/=q.sum()
            err=x-ref
            m["relative_logit_L2"]=float(np.linalg.norm(err)/np.linalg.norm(ref))
            m["KL_F32_to_policy_nats"]=float(np.sum(prob*(np.log(np.maximum(prob,1e-300))-np.log(np.maximum(q,1e-300)))))
            m["top1_equal_to_F32"]=bool(x.argmax()==ref.argmax())
            m["top5_overlap"]=len(set(np.argsort(x)[-5:].tolist())&set(np.argsort(ref)[-5:].tolist()))
        result[mode]=m
    return result

